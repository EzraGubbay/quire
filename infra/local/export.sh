#!/usr/bin/env bash
# Exports every course (all projects of kind=course and everything that hangs off them) from the local stack into
# $QUIRE_LOCAL_DIR/dumps/<timestamp>/ as CSV files plus an import.sql and a copy of their uploaded files.
# The result is what infra/local/migrate-to-pi.sh ships to the deployed instance. Embeddings are not exported;
# run "Reindex" in the course's settings after importing.
set -euo pipefail
cd "$(dirname "$0")/../.."
DIR="${QUIRE_LOCAL_DIR:-$HOME/Desktop/current-uni/quire-local}"
TS="$(date +%Y%m%d-%H%M%S)"
OUT="$DIR/dumps/$TS"
mkdir -p "$OUT/files"
compose() { docker compose -f infra/compose.local.yml "$@"; }
psql_cmd() { compose exec -T db psql -U quire -d quire -v ON_ERROR_STOP=1 -q "$@"; }

# Tables in foreign-key order, each limited to the course projects. The WHERE clauses mirror the schema's FKs.
TABLES=(
  "projects|kind = 'course'"
  "folders|project_id in (select id from projects where kind = 'course')"
  "sessions|project_id in (select id from projects where kind = 'course')"
  "documents|project_id in (select id from projects where kind = 'course')"
  "document_pages|document_id in (select id from documents where project_id in (select id from projects where kind = 'course'))"
  "annotations|project_id in (select id from projects where kind = 'course')"
  "notes|project_id in (select id from projects where kind = 'course')"
  "links|project_id in (select id from projects where kind = 'course')"
  "macros|project_id in (select id from projects where kind = 'course')"
  "chat_threads|project_id in (select id from projects where kind = 'course')"
  "chat_messages|thread_id in (select id from chat_threads where project_id in (select id from projects where kind = 'course'))"
  "assignments|project_id in (select id from projects where kind = 'course')"
  "assignment_questions|assignment_id in (select id from assignments where project_id in (select id from projects where kind = 'course'))"
  "assignment_files|assignment_id in (select id from assignments where project_id in (select id from projects where kind = 'course'))"
  "tests|project_id in (select id from projects where kind = 'course')"
  "test_questions|test_id in (select id from tests where project_id in (select id from projects where kind = 'course'))"
  "reread_items|test_id in (select id from tests where project_id in (select id from projects where kind = 'course'))"
)

echo "Exporting courses to $OUT"
{
  echo "-- Generated by infra/local/export.sh on $TS. Run inside the target's db container:"
  echo "--   psql -U quire -d quire -v ON_ERROR_STOP=1 -f import.sql   (from the directory holding the CSVs)"
  echo "\\set ON_ERROR_STOP on"
  echo "begin;"
} > "$OUT/import.sql"
for entry in "${TABLES[@]}"; do
  table="${entry%%|*}"
  where="${entry#*|}"
  # The db container sees the dumps folder at /dumps.
  psql_cmd -c "\\copy (select * from $table where $where) to '/dumps/$TS/$table.csv' csv header"
  n=$(($(wc -l < "$OUT/$table.csv") - 1))
  echo "  $table: $n rows"
  echo "\\copy $table from '$table.csv' csv header" >> "$OUT/import.sql"
done
echo "commit;" >> "$OUT/import.sql"

# Uploaded files of the exported projects (FILES_DIR/<projectId>/...).
for pid in $(tail -n +2 "$OUT/projects.csv" | cut -d, -f1); do
  if [ -d "$DIR/files/$pid" ]; then
    cp -R "$DIR/files/$pid" "$OUT/files/"
  fi
done
echo "  files: $(find "$OUT/files" -type f | wc -l | tr -d ' ') files"
echo "Done: $OUT"
echo "Migrate with: infra/local/migrate-to-pi.sh $OUT"
