#!/usr/bin/env bash
# Exports every course (all projects of kind=course and everything that hangs off them) from the local stack into
# $QUIRE_LOCAL_DIR/dumps/<timestamp>/: one CSV per table, an import.sql that loads them in foreign-key order with
# explicit column lists, a manifest.txt of row counts, and a copy of the courses' uploaded files.
# The result is what infra/local/migrate-to-pi.sh ships to the deployed instance. Embeddings are not exported;
# run "Reindex" in each course's settings after importing.
set -euo pipefail
cd "$(dirname "$0")/../.."
DIR="${QUIRE_LOCAL_DIR:-$HOME/Desktop/current-uni/quire-local}"
TS="$(date +%Y%m%d-%H%M%S)"
OUT="$DIR/dumps/$TS"
mkdir -p "$OUT/files"
compose() { docker compose -f infra/compose.local.yml "$@"; }
psql_cmd() { compose exec -T db psql -U quire -d quire -v ON_ERROR_STOP=1 -q "$@"; }

COURSES="select id from projects where kind = 'course'"
# Tables in foreign-key order, each limited to the course projects. The WHERE clauses mirror the schema's FKs.
TABLES=(
  "projects|kind = 'course'"
  "folders|project_id in ($COURSES)"
  "sessions|project_id in ($COURSES)"
  "documents|project_id in ($COURSES)"
  "document_pages|document_id in (select id from documents where project_id in ($COURSES))"
  "annotations|project_id in ($COURSES)"
  "notes|project_id in ($COURSES)"
  "links|project_id in ($COURSES)"
  "macros|project_id in ($COURSES)"
  "chat_threads|project_id in ($COURSES)"
  "chat_messages|thread_id in (select id from chat_threads where project_id in ($COURSES))"
  "assignments|project_id in ($COURSES)"
  "assignment_questions|assignment_id in (select id from assignments where project_id in ($COURSES))"
  "assignment_files|assignment_id in (select id from assignments where project_id in ($COURSES))"
  "tests|project_id in ($COURSES)"
  "test_questions|test_id in (select id from tests where project_id in ($COURSES))"
  "reread_items|test_id in (select id from tests where project_id in ($COURSES))"
)

echo "Exporting courses to $OUT"
{
  echo "-- Generated by infra/local/export.sh on $TS. Run from the directory holding the CSVs:"
  echo "--   psql -U quire -d quire -v ON_ERROR_STOP=1 -f import.sql"
  echo "-- Set -v dry_run=1 to load everything and roll back (a rehearsal)."
  echo "\\set ON_ERROR_STOP on"
  echo "begin;"
} > "$OUT/import.sql"
: > "$OUT/manifest.txt"
for entry in "${TABLES[@]}"; do
  table="${entry%%|*}"
  where="${entry#*|}"
  # The db container sees the dumps folder at /dumps.
  psql_cmd -c "\\copy (select * from $table where $where) to '/dumps/$TS/$table.csv' csv header"
  n=$(($(wc -l < "$OUT/$table.csv") - 1))
  # Rows can span lines (multi-line note bodies), so count with Postgres rather than wc.
  n=$(psql_cmd -tAc "select count(*) from $table where $where")
  echo "  $table: $n rows"
  echo "$table $n" >> "$OUT/manifest.txt"
  cols=$(head -1 "$OUT/$table.csv")
  echo "\\copy $table ($cols) from '$table.csv' csv header" >> "$OUT/import.sql"
done
cat >> "$OUT/import.sql" <<'SQL'
\if :{?dry_run}
  \echo 'dry run: rolling back'
  rollback;
\else
  commit;
\endif
SQL

# Uploaded files of the exported projects (FILES_DIR/<projectId>/...).
for pid in $(psql_cmd -tAc "$COURSES"); do
  if [ -d "$DIR/files/$pid" ]; then
    cp -R "$DIR/files/$pid" "$OUT/files/"
  fi
done
echo "files $(find "$OUT/files" -type f | wc -l | tr -d ' ')" >> "$OUT/manifest.txt"
echo "  files: $(find "$OUT/files" -type f | wc -l | tr -d ' ') files"
echo "Done: $OUT"
echo "Migrate with: infra/local/migrate-to-pi.sh $OUT"
